import type { ResolvedTheme, ThemeMode } from '../derive'
import { SEMANTIC_TOKEN_NAMES } from '../theme-spec'
import { CANONICAL_STEPS } from '../canonical'
import { SHADCN_ALIAS_MAP } from '../semantic-map'

function cssVarsBlock(
  theme: ResolvedTheme,
  mode: ThemeMode,
  selector: string,
): string {
  const lines: string[] = [`${selector} {`]

  for (const [scaleName, scale] of Object.entries(theme.primitives)) {
    for (const step of CANONICAL_STEPS) {
      const color = scale[step]
      if (!color) continue
      const [l, c, h] = color.oklch
      lines.push(
        `  --${scaleName}-${step}: oklch(${l.toFixed(3)} ${c.toFixed(3)} ${h.toFixed(1)}); /* ${color.hex} */`,
      )
    }
  }

  for (const name of SEMANTIC_TOKEN_NAMES) {
    const ref = theme.semanticRefs[mode][name]
    // Prefer alias to primitive when ref exists; fg-on-brand may be computed hex
    if (name === 'fg-on-brand') {
      lines.push(`  --${name}: ${theme.semantic[mode][name]};`)
    } else {
      lines.push(`  --${name}: var(--${ref});`)
    }
  }

  for (const [shadcnName] of Object.entries(SHADCN_ALIAS_MAP)) {
    const semantic = SHADCN_ALIAS_MAP[shadcnName]!
    lines.push(`  --${shadcnName}: var(--${semantic});`)
  }

  lines.push(`  --radius: ${theme.radius};`)
  lines.push('}')
  return lines.join('\n')
}

/** CSS Custom Properties — Light (:root) + Dark (.dark). */
export function serializeCss(theme: ResolvedTheme): string {
  const header = [
    '/* Generated by Handstyle — do not edit by hand */',
    `/* Theme: ${theme.spec.name} */`,
    '',
  ].join('\n')
  return `${header}${cssVarsBlock(theme, 'light', ':root')}\n\n${cssVarsBlock(theme, 'dark', '.dark')}\n`
}

/** Tailwind v4 @theme — maps semantic + primitives into --color-*. */
export function serializeTailwindV4(theme: ResolvedTheme): string {
  const lines: string[] = [
    '/* Generated by Handstyle — Tailwind v4 @theme */',
    `@theme inline {`,
    `  --radius-lg: var(--radius);`,
    `  --radius-sm: calc(var(--radius) * 0.6);`,
    `  --radius-md: calc(var(--radius) * 0.8);`,
    `  --radius-xl: calc(var(--radius) * 1.4);`,
  ]

  for (const [scaleName, scale] of Object.entries(theme.primitives)) {
    for (const step of CANONICAL_STEPS) {
      if (!scale[step]) continue
      lines.push(`  --color-${scaleName}-${step}: var(--${scaleName}-${step});`)
    }
  }

  for (const name of SEMANTIC_TOKEN_NAMES) {
    lines.push(`  --color-${name}: var(--${name});`)
  }

  for (const shadcnName of Object.keys(SHADCN_ALIAS_MAP)) {
    lines.push(`  --color-${shadcnName}: var(--${shadcnName});`)
  }

  lines.push('}')
  lines.push('')
  lines.push(serializeCss(theme))
  return lines.join('\n')
}

/** DTCG-ish JSON (W3C Design Tokens). */
export function serializeDtcg(theme: ResolvedTheme): string {
  const color: Record<string, unknown> = {}

  for (const [scaleName, scale] of Object.entries(theme.primitives)) {
    const group: Record<string, unknown> = {}
    for (const step of CANONICAL_STEPS) {
      const c = scale[step]
      if (!c) continue
      group[String(step)] = {
        $type: 'color',
        $value: c.hex,
        $extensions: {
          'handstyle.oklch': c.oklch,
        },
      }
    }
    color[scaleName] = group
  }

  const semantic: Record<string, unknown> = {}
  for (const name of SEMANTIC_TOKEN_NAMES) {
    semantic[name] = {
      $type: 'color',
      $value: {
        light: theme.semantic.light[name],
        dark: theme.semantic.dark[name],
      },
      $extensions: {
        'handstyle.ref': {
          light: theme.semanticRefs.light[name],
          dark: theme.semanticRefs.dark[name],
        },
      },
    }
  }
  color.semantic = semantic

  return JSON.stringify(
    {
      $schema: 'https://design-tokens.github.io/community-group/format/',
      name: theme.spec.name,
      color,
      radius: {
        base: { $type: 'dimension', $value: theme.radius },
      },
    },
    null,
    2,
  )
}

/** Figma plugin payload — collections + variables (idempotent keys). */
export function serializeFigmaPayload(theme: ResolvedTheme): string {
  const primitives = CANONICAL_STEPS.flatMap((step) =>
    Object.entries(theme.primitives).map(([scaleName, scale]) => {
      const c = scale[step]!
      return {
        key: `primitive/${scaleName}/${step}`,
        name: `color/${scaleName}/${step}`,
        type: 'COLOR',
        value: c.hex,
        scopes: ['ALL_FILLS', 'STROKE_COLOR'],
        codeSyntax: { WEB: `var(--${scaleName}-${step})` },
        description: `Primitive ${scaleName}-${step}`,
      }
    }),
  )

  const semantic = (['light', 'dark'] as const).flatMap((mode) =>
    SEMANTIC_TOKEN_NAMES.map((name) => ({
      key: `semantic/${name}`,
      name: `color/${name.replace(/-/g, '/')}`,
      type: 'COLOR',
      mode,
      aliasOf: `primitive/${theme.semanticRefs[mode][name].replace(/^(.*)-(\d+)$/, '$1/$2')}`,
      resolved: theme.semantic[mode][name],
      scopes: name.startsWith('fg-')
        ? ['TEXT_FILL']
        : name.startsWith('border-') || name === 'ring-focus'
          ? ['STROKE_COLOR']
          : ['FRAME_FILL', 'SHAPE_FILL'],
      codeSyntax: { WEB: `var(--${name})` },
      description: `Semantic ${name} (${mode})`,
    })),
  )

  return JSON.stringify(
    {
      version: 1,
      themeName: theme.spec.name,
      collections: [
        { name: 'Primitives', modes: ['Value'] },
        { name: 'Semantic', modes: ['Light', 'Dark'] },
      ],
      variables: { primitives, semantic },
    },
    null,
    2,
  )
}

/** design.md for AI agents. */
export function serializeDesignMd(theme: ResolvedTheme): string {
  const lines = [
    `# ${theme.spec.name} — Design Tokens`,
    '',
    'Generated by Handstyle. Semantic tokens are the API; primitives are implementation detail.',
    '',
    '## Rules',
    '',
    '- Use `--bg-*`, `--fg-*`, `--border-*`, `--status-*`, `--data-*` in UI code.',
    '- Do not hardcode hex in components.',
    '- Marke = `--bg-brand` / shadcn `--primary`. Hover-Fläche = `--bg-subtle` / shadcn `--accent` (nicht die Marke).',
    '- Light/Dark via `.dark` class; same token names.',
    '',
    '## Surfaces (light → dark)',
    '',
    '| Token | Light | Dark |',
    '|-------|-------|------|',
  ]

  for (const name of [
    'bg-canvas',
    'bg-surface',
    'bg-elevated',
    'bg-subtle',
    'bg-muted',
  ] as const) {
    lines.push(
      `| \`--${name}\` | \`${theme.semantic.light[name]}\` | \`${theme.semantic.dark[name]}\` |`,
    )
  }

  lines.push('', '## Brand', '')
  for (const name of [
    'bg-brand',
    'bg-brand-hover',
    'fg-on-brand',
    'fg-brand',
  ] as const) {
    lines.push(
      `- \`--${name}\`: light \`${theme.semantic.light[name]}\` · dark \`${theme.semantic.dark[name]}\``,
    )
  }

  if (theme.exampleFeedbackUsed.length) {
    lines.push(
      '',
      '## Note',
      '',
      `Example feedback hues in use: ${theme.exampleFeedbackUsed.join(', ')}.`,
    )
  }

  lines.push('')
  return lines.join('\n')
}

export type SerializeFormat =
  | 'css'
  | 'tailwind-v4'
  | 'dtcg'
  | 'figma'
  | 'design-md'

export function serialize(
  theme: ResolvedTheme,
  format: SerializeFormat,
): string {
  switch (format) {
    case 'css':
      return serializeCss(theme)
    case 'tailwind-v4':
      return serializeTailwindV4(theme)
    case 'dtcg':
      return serializeDtcg(theme)
    case 'figma':
      return serializeFigmaPayload(theme)
    case 'design-md':
      return serializeDesignMd(theme)
  }
}
